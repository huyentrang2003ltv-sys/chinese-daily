extraWords.forEach(w => {
  if (!existingMap.has(w.title)) {
    currentDict.push(w);
    existingMap.set(w.title, w);
    addedCount++;
  } else {
    // update level if needed
    const existing = existingMap.get(w.title);
    existing.level = w.level;
    if (!existing.exampleSentence && w.exampleSentence) {
      existing.exampleSentence = w.exampleSentence;
      existing.examplePinyin = w.examplePinyin;
      existing.exampleMeaning = w.exampleMeaning;
    }
  }
});

console.log(`Added ${addedCount} new words directly from chart.`);

// Sort by level asc, then by title length/pinyin
currentDict.sort((a, b) => {
  if (a.level !== b.level) return a.level - b.level;
  return a.title.localeCompare(b.title, 'zh-CN');
});

fs.writeFileSync(dictPath, JSON.stringify(currentDict, null, 2), 'utf8');

// Print breakdown
const breakdown = {};
currentDict.forEach(w => {
  breakdown[w.level] = (breakdown[w.level] || 0) + 1;
});
console.log('Final Dictionary Level Breakdown:', breakdown);
console.log('Total words:', currentDict.length);
